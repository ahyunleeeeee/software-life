import streamlit as st

st.set_page_config(page_title="베라 키오스크 🍨", page_icon="🍦", layout="centered")

st.title("🍦 베스킨라빈스 키오스크")
st.write("안녕하세요! 달콤한 아이스크림의 세계에 오신 걸 환영해요 😊")


# -----------------------------
# 1. 매장/포장 선택
# -----------------------------
st.header("1️⃣ 이용 방법 선택")
eat_type = st.radio(
    "매장에서 드시나요, 포장해 가시나요? 😄",
    ("매장 이용 🍽️", "포장 🛍️")
)


# -----------------------------
# 2. 용기 선택
# -----------------------------
st.header("2️⃣ 용기 선택")
container = st.selectbox(
    "원하시는 용기를 골라주세요! 😋",
    ("싱글 레귤러 (1가지)", "싱글킹 (1가지)",
     "더블주니어 (2가지)", "더블레귤러 (2가지)",
     "파인트 (3가지)")
)

# 용기별 가격
price_table = {
    "싱글 레귤러 (1가지)": 3300,
    "싱글킹 (1가지)": 3900,
    "더블주니어 (2가지)": 6200,
    "더블레귤러 (2가지)": 6900,
    "파인트 (3가지)": 8200
}

base_price = price_table[container]


# -----------------------------
# 3. 아이스크림 맛 선택
# -----------------------------
st.header("3️⃣ 아이스크림 맛 선택 🍨")

flavors = [
    "바닐라 🤍", "초콜릿 🍫", "민트초코 🍃🍫", "슈팅스타 🌠",
    "레인보우샤베트 🌈", "엄마는외계인 👽", "아몬드봉봉 ⭐",
    "스트로베리 🍓", "피스타치오 💚", "블루베리 요거트 🫐"
]

# 용기 종류에 따른 선택 가능 개수
if "1가지" in container:
    select_count = 1
elif "2가지" in container:
    select_count = 2
else:
    select_count = 3

selected_flavors = st.multiselect(
    f"👉 {select_count}가지 맛을 골라주세요!",
    flavors,
    max_selections=select_count
)


# -----------------------------
# 4. 결제 화면
# -----------------------------
st.header("4️⃣ 결제하기 💳")

if len(selected_flavors) == select_count:
    st.success("모든 선택이 완료되었습니다! 🎉")

    st.subheader("💰 최종 가격")
    st.write(f"### 👉 **{base_price}원 입니다!**")

    # 🔥 기프티콘 결제 추가
    pay = st.radio(
        "결제 방식을 선택해주세요 😊",
        ("💵 현금 결제", "💳 카드 결제", "🧾 기프티콘 결제")
    )

    if pay == "💵 현금 결제":
        st.info("현금 결제를 선택하셨습니다! 직원에게 현금을 전달해주세요 🙌")

    elif pay == "💳 카드 결제":
        st.info("카드를 단말기에 꽂아주세요! 감사합니다 😊")

    else:  # 기프티콘
        st.info("기프티콘 결제를 선택하셨네요! 📱 바코드를 리더기에 스캔해주세요 🧾✨")

else:
    st.warning("맛을 모두 선택해주세요! 🍨")


# -----------------------------
# 하단 안내
# -----------------------------
st.write("---")
st.write("감사합니다! 맛있게 드세요 😋🍦")

